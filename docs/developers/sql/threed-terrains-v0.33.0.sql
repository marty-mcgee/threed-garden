BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL search_path = public;

ALTER TYPE asset_type ADD VALUE 'threed_terrains';

CREATE TABLE threed_terrains (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id text NOT NULL REFERENCES "user"(id),
  name varchar(255) NOT NULL,
  created_at timestamp NOT NULL DEFAULT now(),
  updated_at timestamp NOT NULL DEFAULT now(),
  CONSTRAINT threed_terrains_name_check CHECK (length(btrim(name)) > 0)
);
CREATE INDEX threed_terrains_owner_name_idx ON threed_terrains(user_id, name);

CREATE TABLE threed_terrain_revisions (
  terrain_id integer NOT NULL REFERENCES threed_terrains(id) ON DELETE RESTRICT,
  revision integer NOT NULL,
  format_version integer NOT NULL DEFAULT 1,
  width_m double precision NOT NULL,
  length_m double precision NOT NULL,
  columns integer NOT NULL,
  rows integer NOT NULL,
  heights_m jsonb NOT NULL,
  appearance jsonb NOT NULL,
  created_at timestamp NOT NULL DEFAULT now(),
  PRIMARY KEY (terrain_id, revision),
  CONSTRAINT threed_terrain_revision_positive CHECK (revision > 0),
  CONSTRAINT threed_terrain_format_version CHECK (format_version = 1),
  CONSTRAINT threed_terrain_width_check CHECK (width_m > 0 AND width_m <= 1000),
  CONSTRAINT threed_terrain_length_check CHECK (length_m > 0 AND length_m <= 1000),
  CONSTRAINT threed_terrain_columns_check CHECK (columns BETWEEN 2 AND 129),
  CONSTRAINT threed_terrain_rows_check CHECK (rows BETWEEN 2 AND 129),
  CONSTRAINT threed_terrain_heights_array CHECK (jsonb_typeof(heights_m) = 'array'),
  CONSTRAINT threed_terrain_appearance_object CHECK (jsonb_typeof(appearance) = 'object')
);

CREATE TABLE project_terrain_placements (
  id text PRIMARY KEY DEFAULT gen_random_uuid()::text,
  user_id text NOT NULL REFERENCES "user"(id),
  project_id integer NOT NULL REFERENCES project(id) ON DELETE CASCADE,
  threed_id integer NOT NULL REFERENCES threed(id),
  terrain_id integer NOT NULL,
  terrain_revision integer NOT NULL,
  center_x_m double precision NOT NULL,
  center_z_m double precision NOT NULL,
  rotation_y_deg double precision NOT NULL,
  scale double precision NOT NULL,
  saved_at timestamp NOT NULL DEFAULT now(),
  CONSTRAINT project_terrain_placements_revision_fk
    FOREIGN KEY (terrain_id, terrain_revision)
    REFERENCES threed_terrain_revisions(terrain_id, revision) ON DELETE RESTRICT,
  CONSTRAINT project_terrain_placements_scale_check CHECK (scale > 0)
);
CREATE UNIQUE INDEX project_terrain_placements_project_idx
  ON project_terrain_placements(project_id);
CREATE INDEX project_terrain_placements_owner_terrain_idx
  ON project_terrain_placements(user_id, terrain_id);
COMMIT;

